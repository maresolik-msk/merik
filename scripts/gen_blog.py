def build_sitemap(posts_by_slug):
    def url(loc, lastmod, freq, prio):
        return (f"  <url>\n    <loc>{loc}</loc>\n    <lastmod>{lastmod}</lastmod>\n"
                f"    <changefreq>{freq}</changefreq>\n    <priority>{prio}</priority>\n  </url>")

    newest = max(p["modified"] for p in posts_by_slug.values())
    out = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
        url(f"{SITE}/", newest, "weekly", "1.0"),
        url(f"{SITE}/features", "2026-07-11", "monthly", "0.9"),
        url(f"{SITE}/how-it-works", "2026-07-11", "monthly", "0.8"),
        url(f"{SITE}/modules", "2026-07-11", "monthly", "0.8"),
        url(f"{SITE}/pricing", newest, "monthly", "0.9"),
        url(f"{SITE}/roi", newest, "monthly", "0.8"),
        url(f"{SITE}/blog/", newest, "weekly", "0.7"),
    ]
    for slug, _, _, _, _ in CARDS:
        p = posts_by_slug.get(slug)
        out.append(url(f"{SITE}/blog/{slug}", p["modified"] if p else "2026-07-16",
                       "monthly", "0.6"))
    out.append("</urlset>")
    return "\n".join(out) + "\n"


def main():
    by_slug = {p["slug"]: p for p in POSTS}
    missing = [s for s in by_slug if s not in CARD_BY_SLUG]
    assert not missing, f"post without a CARDS entry: {missing}"
    for p in POSTS:
        for r in p["related"]:
            assert r in CARD_BY_SLUG, f"{p['slug']} links to unknown post {r}"
        (BLOG / f"{p['slug']}.html").write_text(build_post(p), encoding="utf-8")
    (BLOG / "index.html").write_text(build_index(), encoding="utf-8")
