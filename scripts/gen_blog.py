def j(s):
    """Escape a string for embedding in JSON-LD."""
    return (s.replace("\\", "\\\\").replace('"', '\\"')
             .replace("\n", " ").replace("&amp;", "&").replace("&#8377;", "₹"))


def strip_tags(s):
    return re.sub(r"<[^>]+>", " ", s)


def read_time(post):
    words = len(strip_tags(
        post["lede"] + " ".join(b for _, _, b in post["sections"])
        + " ".join(a for _, a in post["faqs"]) + post["merik"]
    ).split())
    return max(3, round(words / 220))


def card_html(slug, prefix="/"):
    slug_, cat, img, title, blurb = CARD_BY_SLUG[slug]
    return f"""      <a class="blog-card" data-cat="{cat}" href="/blog/{slug}">
        <img class="thumb" src="{prefix}assets/images/blog/{img}.svg" alt="{html.escape(strip_tags(title).strip())}" width="400" height="240" loading="lazy">
        <div class="bc-body"><span class="tag2">{cat}</span>
        <h3>{title}</h3>
        <p>{blurb}</p></div>
      </a>"""


